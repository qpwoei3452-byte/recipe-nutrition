def to_grams(
    amount: float,
    unit: Optional[str],
    ingredient_name: Optional[str] = None
) -> Optional[float]:
    """
    재료의 양과 단위를 g으로 환산합니다.

    Args:
        amount: 수치 (예: 2, 1.5, 0.5)
        unit: 단위 문자열 (예: "개", "큰술", "g", "컵")
        ingredient_name: 표준 재료명 (개수 단위 환산 시 사용)

    Returns:
        그램 수 (환산 불가 시 None)
    """
    if amount is None or amount <= 0:
        return None

    # 단위가 없으면 g으로 간주
    if not unit:
        return float(amount)

    unit = unit.strip()

    # 1) 범용 단위 직접 매칭
    if unit in UNIT_TO_GRAM:
        grams = amount * UNIT_TO_GRAM[unit]
        # 액체류 밀도 보정
        if ingredient_name and ingredient_name in LIQUID_DENSITY:
            grams *= LIQUID_DENSITY[ingredient_name]
        return round(grams, 2)

    # 2) 개수 단위 ("개", "장", "봉지", "캔", "모", "마리", "쪽", "줌", "공기", "인분")
    COUNT_UNITS = {"개", "장", "봉지", "봉", "캔", "모", "마리", "쪽", "줌",
                   "공기", "인분", "단", "통", "포기", "대", "줄기"}
    if unit in COUNT_UNITS:
        if ingredient_name and ingredient_name in ITEM_GRAM:
            return round(amount * ITEM_GRAM[ingredient_name], 2)
        # 재료명 불명 시 None 반환 (누락 목록에 추가됨)
        return None

    # 3) 단위 알 수 없음
    return None


def convert_recipe_ingredient(
    ingredient_name: str,
    amount: Optional[float],
    unit: Optional[str]
) -> tuple[Optional[float], str]:
    """
    레시피 재료 하나를 g으로 환산합니다.

    Returns:
        (gram_amount, 환산_메모)
        예: (100.0, "2개 × 50g"), (None, "단위 환산 불가: '줌'")
    """
    if amount is None:
        return None, "양 정보 없음"

    grams = to_grams(amount, unit, ingredient_name)

    if grams is not None:
        unit_str = unit or "g"
        return grams, f"{amount}{unit_str} → {grams}g"
    else:
        return None, f"단위 환산 불가: '{unit}' (재료: {ingredient_name})"
