def normalize_ingredient(raw_name: str) -> str:
    """
    재료명을 표준명으로 변환합니다.

    1. 공백/특수문자 정리
    2. 정확 매칭 우선
    3. 포함 문자열 매칭 (부분 일치)
    4. 매칭 실패 시 원본 반환

    Args:
        raw_name: 원본 재료명 (예: "달걀 2개", "청양고추(다진)")
    Returns:
        표준명 (예: "계란", "고추(청양)")
    """
    # 전처리: 괄호 안 내용, 숫자+단위 제거 후 공백 정리
    cleaned = re.sub(r'\(.*?\)', '', raw_name)       # 괄호 내용 제거
    cleaned = re.sub(r'\d+[\./\d]*\s*[가-힣a-zA-Z]*', '', cleaned)  # 숫자+단위 제거
    cleaned = cleaned.strip()

    # 1단계: 정확 매칭
    if cleaned in NORMALIZE_MAP:
        return NORMALIZE_MAP[cleaned]

    # 2단계: 원본도 정확 매칭 시도
    if raw_name.strip() in NORMALIZE_MAP:
        return NORMALIZE_MAP[raw_name.strip()]

    # 3단계: 포함 문자열 매칭 (긴 키 우선)
    for key in sorted(NORMALIZE_MAP.keys(), key=len, reverse=True):
        if key in cleaned:
            return NORMALIZE_MAP[key]

    # 4단계: 원본에서 포함 매칭
    for key in sorted(NORMALIZE_MAP.keys(), key=len, reverse=True):
        if key in raw_name:
            return NORMALIZE_MAP[key]

    # 매칭 실패 → 원본 반환 (cleaned 버전)
    return cleaned if cleaned else raw_name.strip()


def extract_ingredient_name(full_text: str) -> tuple[str, Optional[float], Optional[str]]:
    """
    레시피 재료 텍스트에서 재료명, 양, 단위를 분리합니다.

    Args:
        full_text: "계란 2개", "된장 3큰술", "돼지고기(삼겹살) 200g"
    Returns:
        (표준재료명, 양, 단위) 튜플
        예: ("계란", 2.0, "개"), ("된장", 3.0, "큰술")
    """
    # 숫자 + 단위 패턴 추출
    pattern = r'(\d+(?:\.\d+)?(?:/\d+)?)\s*([가-힣a-zA-Z]+)?'
    matches = re.findall(pattern, full_text)

    amount = None
    unit = None

    if matches:
        try:
            raw_amount = matches[-1][0]
            # 분수 처리 (1/2 → 0.5)
            if '/' in raw_amount:
                num, den = raw_amount.split('/')
                amount = float(num) / float(den)
            else:
                amount = float(raw_amount)
            unit = matches[-1][1] if matches[-1][1] else None
        except ValueError:
            pass

    # 재료명만 추출 (숫자, 단위, 공백 제거)
    name_only = re.sub(r'\d+(?:\.\d+)?(?:/\d+)?\s*[가-힣a-zA-Z]*', '', full_text).strip()
    name_only = re.sub(r'\s+', ' ', name_only).strip()

    standard_name = normalize_ingredient(name_only if name_only else full_text)

    return standard_name, amount, unit
